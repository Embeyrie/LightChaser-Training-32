#include <stdio.h>  // 引入标准输入输出库，用于使用 printf 和 scanf 函数

int main() {        // 主函数，程序的入口
    int a, b;       // 声明两个整型变量 a 和 b，用于存储用户输入的数字
    
    // 声明两个指针变量 p1 和 p2
    // &a 表示获取变量 a 的内存地址，p1 指向 a；同理 p2 指向 b
    int *p1 = &a, *p2 = &b; 
    
    int c;          // 声明一个临时变量 c，用于交换时的暂存
    
    printf("要交换的两个数字(如1,2):"); // 打印提示信息，提醒用户输入格式
    scanf("%d,%d", &a, &b);            // 读取用户输入的两个整数，存入 a 和 b 的地址中（注意输入时需要用逗号隔开）
    
    // --- 核心交换逻辑 ---
    c = *p1;        // *p1 表示解引用，获取 p1 指向的值（即 a 的值），并将其赋值给临时变量 c
    *p1 = *p2;      // 将 p2 指向的值（即 b 的值）赋值给 p1 指向的内存空间（即把 b 的值赋给 a）
    *p2 = c;        // 将临时变量 c（原本 a 的值）赋值给 p2 指向的内存空间（即把原 a 的值赋给 b）
    // --------------------
    
    printf("交换后:%d,%d\n", a, b); // 打印交换后的 a 和 b 的值
    
    return 0;       // 程序正常结束，返回 0
}